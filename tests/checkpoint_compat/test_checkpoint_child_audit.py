IDENTITY = {'case': 'authored-P2', 'signed_zero': -0.0, 'one': 1}
CHILD_BYTES = 2 * 1024**2  # This test fixture only; native/P1 limits are unchanged.
ARRAY_OBSERVATION_BYTES = 8 * 1024**2
CACHE_PREFIX = '.result.state.bed.voxel_column.surface_cache.'


def fingerprint(item):
    leaves = {name: value for name, value in arrays(item) if not name.startswith(CACHE_PREFIX)}
    assert sum(value.nbytes for value in leaves.values()) <= ARRAY_OBSERVATION_BYTES
    return {name: (value.dtype.str, value.shape, value.tobytes(order='C')) for name, value in leaves.items()}


def raw_records(path, layout):
    """Caller raw seal: admit all fixed names/stat sizes BEFORE its three hashes."""
    directory = path.lstat()
    assert stat.S_ISDIR(directory.st_mode) and set(p.name for p in path.iterdir()) == set(c._CHILD_NAMES)
    sizes = (layout.checkpoint_json_bytes, *(a.file_bytes for a in layout.archives))
    observations = tuple((path / name).lstat() for name in c._CHILD_NAMES)
    assert all(stat.S_ISREG(s.st_mode) and s.st_size == n for s, n in zip(observations, sizes))
    assert sum(s.st_size for s in observations) == layout.native_child_bytes <= CHILD_BYTES
    return tuple(c.CheckpointRawFile(name, s.st_size, c.sha256_file(path / name),
                                     s.st_dev, s.st_ino, s.st_mtime_ns, s.st_ctime_ns, s.st_mode,
                                     directory.st_dev, directory.st_ino,
                                     directory.st_mtime_ns, directory.st_ctime_ns)
                 for name, s in zip(c._CHILD_NAMES, observations))


def invoke(case, *, path=None, item=None, identity=None, limits=None, layout=None, records=None):
    args, progress, target, policy, expected, held = case
    return c.audit_checkpoint_child(target if path is None else path,
                                    progress if item is None else item,
                                    args[1], args[2], args[6], IDENTITY if identity is None else identity,
                                    limits=policy if limits is None else limits,
                                    expected_layout=expected if layout is None else layout,
                                    raw_files=held if records is None else records)


@pytest.fixture(scope='module')
def native_child(tmp_path_factory):
    args, kw = fixture(wet=True, transport_scheme='upwind', force_final_commit=False)
    kw = {**kw, 'max_report_rows': 4096}
    progress = complete_event(*args, **kw, checkpoint_callback=lambda _progress: True)
    assert type(progress) is EventProgress and progress.status == 'wet'
    # Author a value-preserving repeated reference BEFORE genuine validation
    # and native save. Native checkpoint input validation already requires
    # these two depth fields equal; no physical operand/counter is changed.
    before = fingerprint(progress)
    state = progress.result.state
    np.testing.assert_array_equal(state.storm.depth_m, state.bed.water.depth_m)
    storm = dataclasses.replace(state.storm, depth_m=state.bed.water.depth_m)
    state = dataclasses.replace(state, storm=storm)
    progress = dataclasses.replace(progress, result=dataclasses.replace(progress.result, state=state))
    assert fingerprint(progress) == before
    assert progress.result.state.storm.depth_m is progress.result.state.bed.water.depth_m
    policy = c.CheckpointWriteLimits()
    layout = c.checkpoint_write_budget(progress, args[1], args[2], args[6], IDENTITY, limits=policy)
    assert layout.native_child_bytes <= CHILD_BYTES
    path = c.save_checkpoint(tmp_path_factory.mktemp('genuine_P2') / 'child',
                             progress, args[1], args[2], args[6], IDENTITY)
    return args, progress, path, policy, layout, raw_records(path, layout)



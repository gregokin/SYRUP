def forbidden(*_args, **_kwargs):
    raise BaseException('authored negative tripwire: forbidden delegate entered')


def no_later_native(monkeypatch):
    for name in ('sha256_file', 'checkpoint_write_budget', '_encode_wire', 'load_checkpoint'):
        monkeypatch.setattr(c, name, forbidden)
    monkeypatch.setattr(pc, '_audit_archive', forbidden)



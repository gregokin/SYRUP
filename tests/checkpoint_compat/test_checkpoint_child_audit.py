def test_genuine_private_child_audits_then_unchanged_native_load(native_child, monkeypatch):
    args, progress, path, policy, layout, held = native_child
    before = fingerprint(progress)
    calls = []
    original = pc._audit_archive

    def actual_archive(target, remaining):
        calls.append((Path(target).name, remaining))
        return original(target, remaining)

    monkeypatch.setattr(pc, '_audit_archive', actual_archive)
    audit = invoke(native_child)
    assert type(audit) is c.CheckpointChildAudit
    assert calls == [(c.PAYLOADS[0], policy.max_uncompressed_bytes),
                     (c.PAYLOADS[1], policy.max_uncompressed_bytes - layout.archives[0].npy_bytes)]
    assert audit.raw_files == held and audit.raw_child_bytes == layout.native_child_bytes
    assert audit.uncompressed_payload_bytes == layout.uncompressed_payload_bytes
    assert audit.checkpoint_json_bytes == layout.checkpoint_json_bytes
    assert audit.hash_buffer_pair_bytes == 2 * 1024**2
    assert audit.native_call_multiplicities == c._CHILD_AUDIT_CALLS
    for observed, expected in zip(audit.archives, layout.archives):
        assert observed.filename == expected.filename and observed.uncompressed_bytes == expected.npy_bytes
        assert [(m.key, m.dtype, m.shape, m.npy_bytes) for m in observed.members] == [
            (m.key, m.dtype, m.shape, m.npy_bytes) for m in expected.members]
    loaded = c.load_checkpoint(path, args[1], args[2], args[6], IDENTITY,
                               allow_complete=False, max_bytes=policy.max_uncompressed_bytes)
    assert type(loaded) is EventProgress and loaded.status == 'wet'
    assert fingerprint(loaded) == before == fingerprint(progress)
    assert loaded.result.state.t_s == progress.result.state.t_s and loaded.quiet == progress.quiet
    originals = dict(arrays(progress))
    restored = dict(arrays(loaded))
    for name, value in originals.items():
        if not name.startswith(CACHE_PREFIX):
            assert not np.shares_memory(value, restored[name]), name
    # The companion decoder explicitly sets these arrays readonly. Snapshot
    # array flags are not guessed or required to change by this test.
    for value in (loaded.result.state.storm.soil_water_m,
                  loaded.result.state.storm.depth_m,
                  loaded.result.state.routing_source_elevation_m,
                  loaded.result.state.bed.water.mobile_mass_by_cell_class_kg):
        assert value.flags.writeable is False
    assert raw_records(path, layout) == held



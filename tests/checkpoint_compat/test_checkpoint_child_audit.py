@pytest.mark.parametrize('kind', ['key_order', 'signed_zero', 'int_spelling'])
def test_same_parse_json_refuses_exact_bytes_without_p2_parser(negative_child, kind, monkeypatch):
    path, layout = negative_child[2], negative_child[4]
    target = path / 'checkpoint.json'
    original = target.read_text()
    manifest = json.loads(original)
    if kind == 'key_order':
        changed = json.dumps(dict(reversed(tuple(manifest.items()))), indent=2, allow_nan=False) + '\n'
    elif kind == 'signed_zero':
        assert '"signed_zero": -0.0' in original
        changed = original.replace('"signed_zero": -0.0', '"signed_zero": 0.0 ', 1)
    else:
        manifest['identity']['one'] = 1.0
        changed = json.dumps(manifest, indent=2, allow_nan=False) + '\n'
        assert '  "schema":' in changed
        changed = changed.replace('  "schema":', '"schema":', 1)
    assert json.loads(changed) == json.loads(original) and len(changed.encode()) == layout.checkpoint_json_bytes
    target.write_text(changed)
    records = raw_records(path, layout)
    monkeypatch.setattr(c.json, 'loads', forbidden)
    monkeypatch.setattr(pc, '_audit_archive', forbidden)
    with pytest.raises(SedimentEventError, match='native manifest bytes'):
        invoke(negative_child, records=records)


def _corrupt_native_header(case, kind):
    """Negative only. Use actual NumPy header and ZIP writers, no copied parser."""
    path, layout = case[2], case[4]
    target = path / c.PAYLOADS[0]
    assert target.stat().st_size <= CHILD_BYTES
    with zipfile.ZipFile(target) as archive:
        members = [(info.filename, archive.read(info)) for info in archive.infolist()]
    key = 'run_name.npy' if kind == 'zero_width' else 'voxel_mass_kg.npy'
    index = [name for name, _payload in members].index(key)
    payload = members[index][1]
    source = io.BytesIO(payload)
    version = _format_impl.read_magic(source)
    shape, fortran, dtype = _format_impl._read_array_header(source, version, max_header_size=10000)
    offset = source.tell()
    if kind == 'complex':
        dtype = np.dtype('c8')
    elif kind == 'fortran':
        fortran = True
    elif kind == 'zero_width':
        dtype = np.dtype('S0')
    else:
        # Same product/bytes but a genuinely different Native header shape.
        assert len(shape) == 4
        shape = (shape[1], shape[0], *shape[2:])
        assert shape != layout.archives[0].members[index].shape
    sink = io.BytesIO()
    _format_impl._write_array_header(sink, {'descr': _format_impl.dtype_to_descr(dtype),
                                           'fortran_order': fortran, 'shape': shape}, version)
    assert len(sink.getvalue()) == offset
    members[index] = (key, sink.getvalue() + payload[offset:])
    with zipfile.ZipFile(target, 'w', compression=zipfile.ZIP_STORED) as archive:
        for name, data in members:
            with archive.open(name, 'w', force_zip64=True) as stream:
                stream.write(data)
    assert target.stat().st_size == layout.archives[0].file_bytes
    metadata = path / 'checkpoint.json'
    manifest = json.loads(metadata.read_text())
    manifest['files'][c.PAYLOADS[0]] = c.sha256_file(target)
    metadata.write_text(json.dumps(manifest, indent=2, allow_nan=False) + '\n')
    return raw_records(path, layout)


@pytest.mark.parametrize('kind', ['complex', 'fortran', 'zero_width'])
def test_real_native_header_refusals_propagate_unchanged(negative_child, kind):
    before = fingerprint(negative_child[1])
    records = _corrupt_native_header(negative_child, kind)
    with pytest.raises(pc.PhysicalCheckpointError):
        invoke(negative_child, records=records)
    assert fingerprint(negative_child[1]) == before
    assert raw_records(negative_child[2], negative_child[4]) == records



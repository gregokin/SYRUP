def test_native_repeated_backing_stays_distinct_wire_occurrences(native_child):
    _args, progress, _path, policy, expected, _held = native_child
    metadata = c._WriteLayout(policy, c._write_plain_metadata(IDENTITY, policy))
    references = {}
    c._encode_wire(progress, progress.result.state, references, c._registry(), None, None,
                    _mode=c._LAYOUT_WIRE, _layout=metadata)
    by_object = {}
    for key, value in references.items():
        by_object.setdefault(id(value), []).append(key)
    repeated = [keys for keys in by_object.values() if len(keys) > 1]
    assert repeated, 'the genuine native wet fixture must expose repeated array occurrences'
    audit = invoke(native_child)
    assert tuple(m.key for m in audit.archives[1].members) == tuple(references)
    assert tuple(m.key for m in expected.archives[1].members) == tuple(references)
    assert len(references) > len(by_object)



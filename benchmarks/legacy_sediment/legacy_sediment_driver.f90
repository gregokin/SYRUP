   integer, intent(in) :: n
   integer(8), intent(in) :: a(n)
   write(sg_ucap) tag, int(n, 8)
   write(sg_ucap) a
end subroutine wi8

subroutine write_capture(path)
   character(len=*), intent(in) :: path
   call open_out(path, 'SYRFCAP1')
   sg_tmp2 = d(1, :, :); call wd('PRE_D1  ', sg_tmp2, size(sg_tmp2))
   sg_tmp2 = v; call wd('PRE_V   ', sg_tmp2, size(sg_tmp2))
   sg_tmp2 = r2; call wd('PRE_R2  ', sg_tmp2, size(sg_tmp2))
   call wd('PRE_DOLD', sg_dold, size(sg_dold))

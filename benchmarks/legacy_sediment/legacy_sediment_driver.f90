! Controlled state-and-diagnostics glue for the ORIGINAL MAHLERAN 1.2.3 water + wet-sediment routines (task gpu_sediment, A2).
!
! Links, unchanged: shared_data, parameters_from_xml, ff_type8, infilt, route_water, update_water_flow, flow_detachment,
! raindrop_detachment, diffuse_flow_transport, conc_flow_transport, suspended_transport, flow_distrib, update_sediment_flow, and the
! ISOLATED COPY of route_sediment_xml (only the dry-cell splash branch removed and, in the hooked build, a read-only pre-clip
! recorder). The derived constants of initialize_values_xml.f90 come from `syrup_derived_constants`, a subroutine GENERATED by
! sources.py from verbatim line ranges of the original file. This driver holds NO erosion, deposition, detachment, transport or
! routing equation: it reads state, calls the originals in the order of MAHLERAN_storm_xml.f90 100-173 (infilt, route_water,
! route_sediment_xml, update_water_flow, update_sediment_flow; accumulate_flow is unused by methods 2/5; chemistry and markers are
! absent), and accounts, outside the originals, with expressions that only READ their arrays.
!
! Types: shared_data declares many globals by implicit typing (default REAL, kind 4: dt, dx, dx_m, density, sigma, radius,
! diameter, viscosity, settling_vel, ustar, d50, dstar_const, ...). The module is used unchanged, no -fdefault-real-8. Values
! stored into those kind-4 variables are narrowed exactly as in the original application; this is a precision category, not a bug.
!
! Input/output: little-endian stream files with magic, version, endian marker, tagged blocks with element counts and an EOF
! trailer (see sources.py). A legacy STOP returns status 0, so completion is proven by result.txt carrying the marker, never by
! the exit status. Any non-finite or invalid state ends the run with a NONZERO status (error stop), never repaired.
!
! usage: legacy_sediment_driver input.bin output_dir
program legacy_sediment_driver
use shared_data
use parameters_from_xml, only: Raindrop_detachment_a_parameter_size, Raindrop_detachment_b_parameter_size, &
   Raindrop_detachment_c_parameter_size, Raindrop_detachment_d_parameter_size, Raindrop_detachment_max_parameter_size, &
   Particulate_bound_NH4, Particulate_bound_NO3, Particulate_bound_TN, Particulate_bound_TP, Particulate_bound_IC, &
   Particulate_bound_TC, particle_density, active_layer_sensitivity, KE_model_type, time_step, &
   sediment_routing_solution_method
use syrup_hook
use, intrinsic :: ieee_arithmetic
implicit none
integer :: sg_u, sg_ios, sg_i, sg_j, sg_c, sg_ncap, sg_nsnap, sg_nsteps, sg_nrep_dummy, sg_k, sg_ucap
integer(4) :: sg_hi(14)
real(8) :: sg_hd(5), sg_p(30)
character(len=8) :: sg_magic, sg_tag
character(len=1) :: sg_byte
character(len=4096) :: sg_in, sg_out, sg_path
character(len=32) :: sg_num
real(8), allocatable :: sg_rate(:), sg_scale(:, :)
integer(4), allocatable :: sg_capsteps(:), sg_snapsteps(:)
logical, allocatable :: sg_outlet(:, :), sg_active(:, :), sg_term(:, :)
real(8), allocatable :: sg_led(:, :, :), sg_wst(:, :), sg_cumdet(:, :, :), sg_cumdep(:, :, :), sg_cumclip(:, :, :)
real(8), allocatable :: sg_tmp6(:, :, :), sg_tmp6b(:, :, :), sg_vpre(:, :, :)
real(8), allocatable :: sg_tmp2(:, :), sg_dold(:, :)
integer(8), allocatable :: sg_cnt(:, :)
integer(4), allocatable :: sg_itmp(:, :)
real(8) :: sg_af, sg_aflux, sg_row(13, 6), sg_dtd, sg_dxd
real(8) :: sg_rain, sg_export, sg_oldout, sg_qnow, sg_stepexp, sg_steprain, sg_trial, sg_k_clip, sg_val
real(8) :: sg_loop_s, sg_diag_s, sg_cap_s, sg_surface, sg_prog_s
integer :: sg_nprog
integer(8) :: sg_c0, sg_c1, sg_t0, sg_t1, sg_rate_ticks
logical :: sg_ring, sg_act, sg_docap, sg_dosnap
integer :: sg_wetcount, sg_detcount(6), sg_ncell_active

call get_command_argument(1, sg_in)
call get_command_argument(2, sg_out)
if (len_trim(sg_in) == 0 .or. len_trim(sg_out) == 0) error stop 'usage: legacy_sediment_driver input.bin output_dir'
open(newunit=sg_u, file=trim(sg_in), access='stream', form='unformatted', status='old', action='read')
read(sg_u) sg_magic
if (sg_magic /= 'SYRFSED1') error stop 'bad input magic'
read(sg_u) sg_hi
read(sg_u) sg_hd
if (sg_hi(1) /= 1) error stop 'unsupported input version'
if (sg_hi(2) /= 16909060) error stop 'endian marker mismatch (little-endian stream expected)'
nr2 = sg_hi(3); nc2 = sg_hi(4); ncell1 = sg_hi(5); sg_nsteps = sg_hi(6)
if (sg_hi(7) /= 6) error stop 'six grain classes required'
iroute = sg_hi(8)
if (iroute /= 2 .and. iroute /= 5) error stop 'iroute must be 2 or 5'
if (sg_hi(9) /= 2) error stop 'sediment routing selector 2 (Crank-Nicolson) required'
inf_model = sg_hi(10); inf_type = sg_hi(11)
if (inf_model /= 1 .or. inf_type /= 1) error stop 'only infiltration model 1 / type 1 is supported by this glue'
sg_ncap = sg_hi(13); sg_nsnap = sg_hi(14)
if (nr2 < 3 .or. nc2 < 3 .or. sg_nsteps < 1 .or. ncell1 < 1) error stop 'invalid header dimensions'
nr = nr2 - 1; nc = nc2 - 1; nr1 = nr; nc1 = nc; ncell = nr * nc
dt = real(sg_hd(1)); dx = real(sg_hd(2)); dy = dx; dx_m = real(sg_hd(3)); dtdx = dt / dx
if (dble(dt) /= sg_hd(1) .or. dble(dx) /= sg_hd(2)) error stop 'inexact default REAL dt/dx'
ff_type = 1; ndirn = 4; ksat_mod = 1.d0; psi_mod = 1.d0; MiC = 0

allocate(order(ncell1, 3), aspect(nr2, nc2), rmask(nr2, nc2), slope(nr2, nc2), ff(nr2, nc2))
allocate(d(2, nr2, nc2), q(2, nr2, nc2), qin(2, nr2, nc2), v(nr2, nc2), v1(nr2, nc2), qsum(nr2, nc2))
allocate(excess(nr2, nc2), cum_inf(nr2, nc2), cum_inf_p(nr2, nc2), cum_drain(nr2, nc2), stmax(nr2, nc2))
allocate(theta(nr2, nc2), theta_sat(nr2, nc2), ksat(nr2, nc2), psi(nr2, nc2), pave(nr2, nc2), r2(nr2, nc2))
allocate(drain_par(nr2, nc2), t_ponding(nr2, nc2), sg_scale(nr2, nc2), sg_outlet(nr2, nc2), sg_active(nr2, nc2))
allocate(sg_term(nr2, nc2))
allocate(d_soil(6, 2, nr2, nc2), q_soil(6, 2, nr2, nc2), qsedin(6, 2, nr2, nc2), v_soil(6, nr2, nc2))
allocate(veg(nr2, nc2), sed_propn(6, nr2, nc2), detach_soil(6, nr2, nc2), depos_soil(6, nr2, nc2), add_soil(6, nr2, nc2))
allocate(sed_temp(6, nr2, nc2), amm_q(6, nr2, nc2), nit_q(6, nr2, nc2), TN_q(6, nr2, nc2), TP_q(6, nr2, nc2))
allocate(IC_q(6, nr2, nc2), TC_q(6, nr2, nc2))
allocate(sed_tot(nr2, nc2), detach_tot(nr2, nc2), depos_tot(nr2, nc2), z_change(nr2, nc2), amm_tot(nr2, nc2))
allocate(nit_tot(nr2, nc2), TN_tot(nr2, nc2), TP_tot(nr2, nc2), IC_tot(nr2, nc2), TC_tot(nr2, nc2))
allocate(raindrop_detach_tot(nr2, nc2), flow_detach_tot(nr2, nc2))
allocate(syrup_trial(6, nr2, nc2), syrup_clip_factor(6, nr2, nc2))
d = 0; q = 0; qin = 0; v = 0; v1 = 0; qsum = 0; excess = 0; cum_inf_p = 0; cum_drain = 0; r2 = 0; t_ponding = -9999
d_soil = 0; q_soil = 0; qsedin = 0; v_soil = 0; add_soil = 0; sed_temp = 0; detach_soil = 0; depos_soil = 0
amm_q = 0; nit_q = 0; TN_q = 0; TP_q = 0; IC_q = 0; TC_q = 0
sed_tot = 0; detach_tot = 0; depos_tot = 0; z_change = 0; amm_tot = 0; nit_tot = 0; TN_tot = 0; TP_tot = 0; IC_tot = 0
TC_tot = 0; raindrop_detach_tot = 0; flow_detach_tot = 0; syrup_trial = 0; syrup_clip_factor = 0
allocate(sg_rate(sg_nsteps), sg_capsteps(max(sg_ncap, 1)), sg_snapsteps(max(sg_nsnap, 1)))

call rd_i('ASPECT  ', aspect, size(aspect))
call rd_d('RMASK   ', rmask, size(rmask))
call rd_d('SLOPE   ', slope, size(slope))
call rd_d('FF      ', ff, size(ff))
call rd_d('KSAT    ', ksat, size(ksat))
call rd_d('PSI     ', psi, size(psi))
call rd_d('PAVE    ', pave, size(pave))
call rd_d('DRAINPAR', drain_par, size(drain_par))
call rd_d('THETASAT', theta_sat, size(theta_sat))
call rd_d('THETA   ', theta, size(theta))
call rd_d('CUMINF  ', cum_inf, size(cum_inf))
call rd_d('STMAX   ', stmax, size(stmax))
call rd_d('SCALE   ', sg_scale, size(sg_scale))
allocate(sg_itmp(nr2, nc2))
call rd_i('OUTLET  ', sg_itmp, size(sg_itmp)); sg_outlet = sg_itmp == 1
call rd_i('ACTIVE  ', sg_itmp, size(sg_itmp)); sg_active = sg_itmp == 1
deallocate(sg_itmp)
call rd_d('VEG     ', veg, size(veg))
call rd_d('SEDPROPN', sed_propn, size(sed_propn))
call rd_i('ORDER   ', order, size(order))
call rd_d('RATES   ', sg_rate, size(sg_rate))
call rd_i('CAPSTEPS', sg_capsteps, sg_ncap)
call rd_i('SNAPSTEP', sg_snapsteps, sg_nsnap)
call rd_d('SEDPARAM', sg_p, 30)
call rd_tag('SYREOF01', 0_8)
read(sg_u, iostat=sg_ios) sg_byte
if (sg_ios == 0) error stop 'trailing bytes after the input trailer'
close(sg_u)
if (any(.not. ieee_is_finite(sed_propn)) .or. any(sed_propn < 0.d0)) error stop 'invalid grain fractions'
if (any(.not. ieee_is_finite(veg))) error stop 'invalid vegetation'
if (any(.not. ieee_is_finite(sg_rate)) .or. any(sg_rate < 0.d0)) error stop 'invalid rain rates'
if (any(.not. ieee_is_finite(sg_p))) error stop 'invalid sediment parameters'

! parameters_from_xml entities as read by read_parameters_from_xml_file (double precision), then the ORIGINAL initializer lines
Raindrop_detachment_a_parameter_size = sg_p(1:6)
Raindrop_detachment_b_parameter_size = sg_p(7:12)
Raindrop_detachment_c_parameter_size = sg_p(13:18)
Raindrop_detachment_d_parameter_size = sg_p(19:24)
Raindrop_detachment_max_parameter_size = sg_p(25:30)
Particulate_bound_NH4 = 0.d0; Particulate_bound_NO3 = 0.d0; Particulate_bound_TN = 0.d0
Particulate_bound_TP = 0.d0; Particulate_bound_IC = 0.d0; Particulate_bound_TC = 0.d0
time_step = sg_hd(1); particle_density = sg_hd(4); active_layer_sensitivity = sg_hd(5)
KE_model_type = sg_hi(12); sediment_routing_solution_method = sg_hi(9)
call syrup_derived_constants

sg_term = sg_active .and. aspect == 0 .and. .not. sg_outlet
sg_ncell_active = count(sg_active)
sg_dtd = dble(dt); sg_dxd = dble(dx)
sg_af = dble(dx) * dble(dy) * dble(density) * 1.d-6      ! kg per mm of mobile depth in one cell (phase7b audit conversion)
sg_aflux = dble(dx) * dble(density) * 1.d-6 * dble(dt)   ! kg per (mm2/s) over one step (legacy `uc`)
allocate(sg_led(13, 6, sg_nsteps), sg_wst(4, sg_nsteps), sg_cnt(7, sg_nsteps))
allocate(sg_cumdet(6, nr2, nc2), sg_cumdep(6, nr2, nc2), sg_cumclip(6, nr2, nc2), sg_tmp6(6, nr2, nc2))
sg_led = 0; sg_wst = 0; sg_cnt = 0; sg_cumdet = 0; sg_cumdep = 0; sg_cumclip = 0
if (sg_ncap > 0) allocate(sg_tmp6b(6, nr2, nc2), sg_vpre(6, nr2, nc2), sg_dold(nr2, nc2))
allocate(sg_tmp2(nr2, nc2))
sg_rain = 0; sg_export = 0; sg_loop_s = 0; sg_diag_s = 0; sg_cap_s = 0; sg_prog_s = 0; sg_rate_ticks = 0
sg_nprog = max(1, int(60.d0 / dble(dt)))

call system_clock(sg_c0, sg_rate_ticks)
do iter = 1, sg_nsteps
   r2 = sg_rate(iter) * sg_scale
   sg_steprain = sum(r2, mask=sg_active) * dble(dt) * dble(dx)**2 * 1.d-9
   sg_rain = sg_rain + sg_steprain
   sg_docap = any(sg_capsteps(1:sg_ncap) == iter)
   sg_dosnap = any(sg_snapsteps(1:sg_nsnap) == iter)
   if (sg_docap) sg_dold = d(1, :, :)   ! the PREVIOUS step's depth (what the SYRUP replay feeds the laws by default)
   call infilt
   sg_oldout = sum(q(1, :, :), mask=sg_outlet)
   call route_water
   if (.not. all(ieee_is_finite(d(2, :, :)))) error stop 'nonfinite depth'
   if (.not. all(ieee_is_finite(q(2, :, :)))) error stop 'nonfinite discharge'
   if (any(d(2, :, :) < 0.d0) .or. any(q(2, :, :) < 0.d0)) error stop 'negative depth or discharge'
   sg_qnow = sum(q(2, :, :), mask=sg_outlet) * dble(dx) * 1.d-9
   sg_stepexp = .5d0 * dble(dt) * dble(dx) * (sg_oldout + sum(q(2, :, :), mask=sg_outlet)) * 1.d-9
   sg_export = sg_export + sg_stepexp

   if (sg_docap) then
      call system_clock(sg_t0)
      sg_vpre = v_soil
      call system_clock(sg_t1); sg_cap_s = sg_cap_s + dble(sg_t1 - sg_t0) / dble(sg_rate_ticks)
   endif
   syrup_trial = 0.d0; syrup_clip_factor = 0.d0
   call route_sediment_xml
   if (.not. all(ieee_is_finite(d_soil(:, 2, :, :)))) error stop 'nonfinite mobile depth'
   if (any(d_soil(:, 2, :, :) < 0.d0)) error stop 'negative mobile depth after the original clip'

   call system_clock(sg_t0)
   ! ---- accounting that only READS the original arrays (units: kg per step, kg/s for the outlet flux) ----
   sg_row = 0.d0
   sg_wetcount = 0; sg_detcount = 0
   do sg_j = 1, nc2
      do sg_i = 1, nr2
         sg_ring = (sg_i == 1 .or. sg_i == nr2 .or. sg_j == 1 .or. sg_j == nc2)
         sg_act = (.not. sg_ring) .and. (rmask(sg_i, sg_j) >= 0.d0)
         do sg_c = 1, 6
            sg_val = depos_soil(sg_c, sg_i, sg_j) * dble(dt) * sg_af
            sg_cumdep(sg_c, sg_i, sg_j) = sg_cumdep(sg_c, sg_i, sg_j) + sg_val
            if (sg_ring) then
               sg_row(4, sg_c) = sg_row(4, sg_c) + sg_val
            elseif (.not. sg_act) then
               sg_row(5, sg_c) = sg_row(5, sg_c) + sg_val
            else
               sg_row(2, sg_c) = sg_row(2, sg_c) + sg_val
               if (sg_term(sg_i, sg_j)) then
                  sg_row(3, sg_c) = sg_row(3, sg_c) + sg_val
                  sg_row(9, sg_c) = sg_row(9, sg_c) + d_soil(sg_c, 2, sg_i, sg_j) * sg_af
               endif
               sg_val = detach_soil(sg_c, sg_i, sg_j) * dble(dt) * sg_af
               sg_row(1, sg_c) = sg_row(1, sg_c) + sg_val
               sg_cumdet(sg_c, sg_i, sg_j) = sg_cumdet(sg_c, sg_i, sg_j) + sg_val
               if (detach_soil(sg_c, sg_i, sg_j) > 0.d0) sg_detcount(sg_c) = sg_detcount(sg_c) + 1
               sg_row(7, sg_c) = sg_row(7, sg_c) + d_soil(sg_c, 1, sg_i, sg_j) * sg_af
               sg_row(8, sg_c) = sg_row(8, sg_c) + d_soil(sg_c, 2, sg_i, sg_j) * sg_af
               sg_trial = syrup_trial(sg_c, sg_i, sg_j)
               if (sg_trial < 0.d0) then   ! the ACTUAL unclipped trial recorded by the hook, not a balance residual
                  sg_val = -sg_trial * syrup_clip_factor(sg_c, sg_i, sg_j) * sg_af
                  sg_row(6, sg_c) = sg_row(6, sg_c) + sg_val
                  sg_cumclip(sg_c, sg_i, sg_j) = sg_cumclip(sg_c, sg_i, sg_j) + sg_val
               endif
               if (sg_outlet(sg_i, sg_j)) then
                  sg_row(10, sg_c) = sg_row(10, sg_c) + 0.5d0 * sg_aflux * (q_soil(sg_c, 1, sg_i, sg_j) + q_soil(sg_c, 2, sg_i, sg_j))
                  sg_row(11, sg_c) = sg_row(11, sg_c) + sg_aflux * q_soil(sg_c, 2, sg_i, sg_j)
                  sg_row(12, sg_c) = sg_row(12, sg_c) + q_soil(sg_c, 2, sg_i, sg_j) * dble(dx) * dble(density) * 1.d-6
               endif
            endif
         enddo
         if (sg_act .and. d(1, sg_i, sg_j) > 0.d0) sg_wetcount = sg_wetcount + 1
      enddo
   enddo
   sg_led(:, :, iter) = sg_row
   sg_cnt(1, iter) = sg_wetcount
   sg_cnt(2:7, iter) = sg_detcount
   sg_surface = sum(d(2, :, :), mask=sg_active) * dble(dx)**2 * 1.d-9
   sg_wst(1, iter) = sg_qnow; sg_wst(2, iter) = sg_stepexp; sg_wst(3, iter) = sg_surface; sg_wst(4, iter) = sg_steprain
   if (.not. all(ieee_is_finite(sg_row))) error stop 'nonfinite sediment accounting'
   call system_clock(sg_t1); sg_diag_s = sg_diag_s + dble(sg_t1 - sg_t0) / dble(sg_rate_ticks)
   if (mod(iter, sg_nprog) == 0 .or. iter == sg_nsteps) then
      ! flushed progress at <= 60 simulated seconds: iteration, model time and the accumulated measured loop time EXCLUDING progress
      ! I/O; no field scan. The write itself is timed separately (PROGRESS_SECONDS) and subtracted from every loop timer.
      call system_clock(sg_t0)
      write(0, '(A,I0,A,I0,A,F12.3,A,F12.3,A)') 'legacy_sediment_driver: step ', iter, ' of ', sg_nsteps, ' t=', &
         dble(iter) * dble(dt), ' s, measured loop ', dble(sg_t0 - sg_c0) / dble(sg_rate_ticks) - sg_prog_s, ' s'
      flush(0)
      call system_clock(sg_t1); sg_prog_s = sg_prog_s + dble(sg_t1 - sg_t0) / dble(sg_rate_ticks)
   endif

   if (sg_docap .or. sg_dosnap) then
      call system_clock(sg_t0)
      write(sg_num, '(I6.6)') iter
      if (sg_docap) call write_capture(trim(sg_out) // '/capture_' // trim(sg_num) // '.bin')
      if (sg_dosnap) call write_snapshot(trim(sg_out) // '/snapshot_' // trim(sg_num) // '.bin')
      call system_clock(sg_t1); sg_cap_s = sg_cap_s + dble(sg_t1 - sg_t0) / dble(sg_rate_ticks)
   endif

   call update_water_flow
   call update_sediment_flow
enddo
call system_clock(sg_c1)
sg_loop_s = dble(sg_c1 - sg_c0) / dble(sg_rate_ticks) - sg_prog_s   ! progress I/O excluded from the loop timer

! ---- outputs (outside the timed loop) ----
call open_out(trim(sg_out) // '/ledger.bin', 'SYRFOUT1')
call wd('LEDGER  ', sg_led, size(sg_led))
call wd('WATER   ', sg_wst, size(sg_wst))
call wi8('COUNTS  ', sg_cnt, size(sg_cnt))
call close_out
call open_out(trim(sg_out) // '/final_maps.bin', 'SYRFOUT1')
call wd('CUMDET  ', sg_cumdet, size(sg_cumdet))
call wd('CUMDEP  ', sg_cumdep, size(sg_cumdep))
call wd('CUMCLIP ', sg_cumclip, size(sg_cumclip))
sg_tmp6 = d_soil(:, 1, :, :) * sg_af
call wd('MOBILE  ', sg_tmp6, size(sg_tmp6))
sg_tmp2 = d(1, :, :); call wd('DEPTH_MM', sg_tmp2, size(sg_tmp2))
sg_tmp2 = v; call wd('VELOC_MM', sg_tmp2, size(sg_tmp2))
sg_tmp2 = cum_inf; call wd('SOILW_MM', sg_tmp2, size(sg_tmp2))
sg_tmp2 = q(1, :, :); call wd('DISCH_MM', sg_tmp2, size(sg_tmp2))
allocate(sg_itmp(nr2, nc2)); sg_itmp = merge(1, 0, sg_term)
call wi('TERMINAL', sg_itmp, size(sg_itmp))
deallocate(sg_itmp)
call close_out

open(newunit=sg_u, file=trim(sg_out) // '/result.txt', status='new', action='write')
write(sg_u, '(A,ES25.16E3)') 'LOOP_SECONDS ', sg_loop_s
write(sg_u, '(A,ES25.16E3)') 'DIAG_SECONDS ', sg_diag_s
write(sg_u, '(A,ES25.16E3)') 'CAPTURE_SECONDS ', sg_cap_s
write(sg_u, '(A,ES25.16E3)') 'PROGRESS_SECONDS ', sg_prog_s
write(sg_u, '(A,ES25.16E3)') 'KERNEL_SECONDS ', sg_loop_s - sg_diag_s - sg_cap_s
write(sg_u, '(A,I0)') 'STEPS ', sg_nsteps
write(sg_u, '(A,I0)') 'IROUTE ', iroute
write(sg_u, '(A,I0)') 'NR2 ', nr2
write(sg_u, '(A,I0)') 'NC2 ', nc2
write(sg_u, '(A,L1)') 'HOOK_CALLED ', syrup_hook_called
write(sg_u, '(A,I0)') 'ACTIVE_CELLS ', sg_ncell_active
write(sg_u, '(A,ES25.16E3)') 'RAIN_M3 ', sg_rain
write(sg_u, '(A,ES25.16E3)') 'EXPORT_M3 ', sg_export
write(sg_u, '(A,ES25.16E3)') 'SURFACE_M3 ', sum(d(1, :, :), mask=sg_active) * dble(dx)**2 * 1.d-9
write(sg_u, '(A,ES25.16E3)') 'SOIL_M3 ', sum(cum_inf, mask=sg_active) * dble(dx)**2 * 1.d-9
write(sg_u, '(A,ES25.16E3)') 'DRAIN_M3 ', sum(cum_drain, mask=sg_active) * dble(dx)**2 * 1.d-9
write(sg_u, '(A,ES25.16E3)') 'AF_KG_PER_MM ', sg_af
write(sg_u, '(A,ES25.16E3)') 'DX_MM ', sg_dxd
write(sg_u, '(A,ES25.16E3)') 'DENSITY_G_CM3 ', dble(density)   ! the kind-4 (widened) density the original routines actually use
write(sg_u, '(A,ES25.16E3)') 'DT_S ', sg_dtd
write(sg_u, '(A)') 'SYRUP_LEGACY_SEDIMENT_COMPLETE'
close(sg_u)

contains

subroutine rd_tag(tag, n)
   character(len=8), intent(in) :: tag
   integer(8), intent(in) :: n
   integer(8) :: cnt
   read(sg_u) sg_tag, cnt
   if (sg_tag /= tag .or. cnt /= n) then
      write(*, '(A,A,A,A,I0)') 'block mismatch: expected ', tag, ' got ', sg_tag, cnt
      error stop 'input block mismatch'
   endif
end subroutine rd_tag

subroutine rd_d(tag, a, n)
   character(len=8), intent(in) :: tag
   integer, intent(in) :: n
   real(8), intent(out) :: a(n)
   call rd_tag(tag, int(n, 8))
   read(sg_u) a
end subroutine rd_d

subroutine rd_i(tag, a, n)
   character(len=8), intent(in) :: tag
   integer, intent(in) :: n
   integer(4), intent(out) :: a(n)
   call rd_tag(tag, int(n, 8))
   if (n > 0) read(sg_u) a
end subroutine rd_i

subroutine open_out(path, magic)
   character(len=*), intent(in) :: path, magic
   open(newunit=sg_ucap, file=path, access='stream', form='unformatted', status='new', action='write')
   write(sg_ucap) magic
end subroutine open_out

subroutine close_out
   write(sg_ucap) 'SYREOF01', 0_8
   close(sg_ucap)
end subroutine close_out

subroutine wd(tag, a, n)
   character(len=8), intent(in) :: tag
   integer, intent(in) :: n
   real(8), intent(in) :: a(n)
   write(sg_ucap) tag, int(n, 8)
   write(sg_ucap) a
end subroutine wd

subroutine wi(tag, a, n)

def base_blob(rel: str) -> bytes:
    if not (GIT_DIR / "objects").is_dir():
        fail(f"the immutable base object store is missing: {GIT_DIR} (set SYRUP_BASE_GIT_DIR); no ambient HEAD fallback exists")
    done = subprocess.run(["git", f"--git-dir={GIT_DIR}", "show", f"{BASE}:{rel}"], capture_output=True, check=False)
    if done.returncode != 0:
        fail(f"{rel} is not readable at base {BASE}: {done.stderr.decode()[:160]}")
    return done.stdout



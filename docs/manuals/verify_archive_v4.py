def _paragraphs(xml: str) -> list[tuple[int, str]]:
    """(heading level or 0, plain text) for every paragraph of word/document.xml in document order (table cell paragraphs included)."""
    out = []
    for m in re.finditer(r"<w:p[ >].*?</w:p>", xml, re.S):
        para = m.group(0)
        st = re.search(r'<w:pStyle w:val="Heading(\d)"', para)
        out.append((int(st.group(1)) if st else 0, re.sub(r"<[^>]+>", "", para)))
    return out


def phase25_section(xml: str, marker: str, level: int, end_level: int) -> str | None:
    """The text of the Phase 2.5 SECTION only: from the heading containing `marker` to the next heading of level <= `end_level` (or the end)."""
    paras = _paragraphs(xml)
    start = next((i for i, (lv, t) in enumerate(paras) if lv == level and marker in t), None)
    if start is None:
        return None
    end = next((j for j in range(start + 1, len(paras)) if 0 < paras[j][0] <= end_level), len(paras))
    return "\n".join(t for _, t in paras[start:end])


# Provisional / unfinished-release markers that a FINAL Phase 2.5 section must not contain. The generic word "pending" is NOT banned: an honest final limit such as "pending storm, recession and in-flight-day files are
# not supported" is correct. Only unfinished-release uses are refused: "pending" followed (same sentence, nearby) by Root / final / acceptance / identity / publication / commit words, and the draft markers.
PROVISIONAL_PATTERNS = (r"\bDRAFT\b", r"draft_unaccepted", r"intentionally empty", r"to be (?:filled|completed)", r"@RELEASE_[A-Z0-9_]+@", r"\bplaceholders?\b", r"\bTBD\b", r"\bnot (?:yet )?delivered\b",
                        r"\bpending\b(?=[^.\n]{0,48}\b(?:root|final|acceptance|accepted|identity|identities|publication|published|commit|manifest|qualification)\b)",
                        r"\b(?:root|final|acceptance|identity|identities|commit|manifest)\b[^.\n]{0,24}\bpending\b", r"\bin qualification\b", r"\bGPU[^.\n]{0,40}\bin progress\b")


def section_checks(sect: str | None, p25: dict, mode: str, physics: bool) -> dict:
    """Mode-aware checks of the NEW Phase 2.5 section only (the historical chapters may legitimately use the words draft / pending / history)."""
    if sect is None:
        return {"phase25_section_heading": False}
    low = sect.lower()
    res = {"phase25_section_heading": True}
    label = "draft" if mode == "draft" else "accepted"
    res["identity_table_title"] = f"Phase 2.5 identity ({label})" in sect
    if physics:
        res["add_and_cap_declared_adaptation"] = "user-selected adaptation" in sect
    if mode == "draft":
        res["draft_wording"] = ("DRAFT" in sect) and (("not accepted" in low) or ("unaccepted" in low) or ("neither accepted" in low))          # (A and (B or C)) explicitly: a draft says it is not accepted
        res["pending_visible_when_pending"] = ("pending" in sect) if any(p25[k] is None for k in ("source_commit", "syrup_package_sha256", "whole_phase_acceptance_sha256")) else True
        res["status_draft_visible"] = p25["status"] == "draft_unaccepted" and "draft_unaccepted" in sect
    else:
        res["status_accepted_visible"] = p25["status"] == "accepted_bounded" and "accepted_bounded" in sect
        hits = [pat for pat in PROVISIONAL_PATTERNS if re.search(pat, sect, flags=0 if pat.startswith(r"\bDRAFT") else re.IGNORECASE)]   # DRAFT is case-sensitive; the rest case-insensitive
        res["no_provisional_wording"] = not hits
        i = low.find("physical checkpoint")
        res["physical_checkpoint_text_present"] = i >= 0 and len(sect[i:]) > 400                   # a genuine subsection, never the provisional empty one
        res["limits_present"] = "not claimed" in low or "limits" in low
    return res


def docx_checks(name: str, meta: dict, mode: str) -> dict:
    try:
        z = zipfile.ZipFile(HERE / name)
        bad = z.testzip()
    except (zipfile.BadZipFile, OSError, zlib_error) as exc:
        fail(f"{name}: unreadable zip ({type(exc).__name__}: {exc})")
    if bad is not None:
        fail(f"{name}: zip CRC failure")
    names = set(z.namelist())
    rels = [n for n in names if n.endswith(".rels")]
    for n in names:
        if n.endswith((".xml", ".rels")):
            try:
                minidom.parseString(z.read(n))
            except (ExpatError, zipfile.BadZipFile, zlib_error) as exc:
                fail(f"{name}: part {n} does not parse ({type(exc).__name__})")
    for r in rels:  # every INTERNAL relationship target must exist
        base_dir = Path(r).parent.parent
        for rel in minidom.parseString(z.read(r)).getElementsByTagName("Relationship"):
            if rel.getAttribute("TargetMode") == "External":
                continue
            tgt = rel.getAttribute("Target")
            path = os.path.normpath(str(base_dir / tgt)).lstrip("/") if not tgt.startswith("/") else tgt.lstrip("/")
            if path not in names:
                fail(f"{name}: relationship target missing: {r} -> {tgt}")
    text = lambda x: re.sub(r"<[^>]+>", "", x)
    xml = z.read("word/document.xml").decode()
    doc = text(xml)
    foot = "".join(text(z.read(n).decode()) for n in sorted(names) if n.startswith("word/footer"))
    if re.search(r"@RELEASE_|\{\{[a-z0-9_]+\}\}", doc):
        fail(f"{name}: unresolved release tokens")
    c1, p15, p2 = meta["subsurface_release"], meta["native_phase15"], meta["native_phase2"]
    ids = {"c1_syrup": c1["syrup_commit"], "c1_leaf": c1["leaf_commit"], "c1_masy": c1["masy_commit"], "maple_9f": c1["maple_native_commit"], "n15_package": p15["syrup_package_sha256"],
           "n15_receipt": p15["whole_phase_receipt_sha256"], "p2_source_commit": p2["source_commit"], "p2_package": p2["syrup_package_sha256"], "p2_manifest": p2["source_manifest_sha256"],
           "p2_acceptance": p2["whole_phase_acceptance_sha256"]}
    p25 = meta["native_phase25"]
    for key in ("leaf_package_sha256", "leaf_external_helper_sha256", "maple_native_package_sha256", "maple_native_commit", "leaf_source_commit", "source_commit", "syrup_package_sha256",
                "source_manifest_sha256", "whole_phase_acceptance_sha256", "cache_component_package_sha256", "lifecycle_component_package_sha256", "held_context_component_package_sha256",
                "frames_component_package_sha256"):
        if p25[key] is not None:  # EVERY actual (non-null) Phase 2.5 identity must be in the text; final mode (load_metadata) guarantees the mandatory ones are non-null
            ids["p25_" + key] = p25[key]
    present = {k: (v in doc) for k, v in ids.items()}
    missing = [k for k, v in present.items() if not v]
    if missing:
        fail(f"{name}: identities missing from the document text: {missing}")
    physics = "Physics" in name
    sect = phase25_section(xml, "Phase 2.5" if physics else "15.7 Phase 2.5", 1 if physics else 2, 1 if physics else 2)
    sections = {"phase2_section": "Native Phase 2 source identity" in doc, **section_checks(sect, p25, mode, physics)}
    if not all(sections.values()):
        fail(f"{name}: required Phase 2.5 section checks failed ({mode} mode): {sections}")
    media = [n for n in names if n.startswith("word/media")]
    if not media:
        fail(f"{name}: no embedded figure")
    status_word = meta["release_status"].capitalize()
    if mode == "draft" and not (foot.strip().startswith("Draft") and "Phase 2.5" in foot):
        fail(f"{name}: a draft build must be labelled Draft with the Phase 2.5 status in its footer, got {foot.strip()[:100]!r}")
    if mode == "final" and not (foot.strip().startswith("Final") and "accepted_bounded" in foot):
        fail(f"{name}: a final build must be labelled Final with the accepted Phase 2.5 status, got {foot.strip()[:100]!r}")
    return {"file": name, "sha256": sha((HERE / name).read_bytes()), "bytes": (HERE / name).stat().st_size, "zip_crc_ok": True, "xml_and_relationship_parts_parse": True,
            "relationship_parts": len(rels), "internal_relationship_targets_exist": True, "media_count": len(media), "unresolved_source_tokens": False, "identities_present": present,
            "sections_visible": sections, "footer": foot.strip()[:140], "status_word": status_word}


def fenced_and_examples() -> tuple[list, list]:
    blocks = []
    for src in ("user_guide.md", "model_structure_and_physics.md", "cli_reference.md"):
        for i, m in enumerate(re.finditer(r"```(\w+)\n(.*?)```", (HERE / src).read_text(), re.S)):
            lang, body = m[1], m[2]
            if lang in ("bash", "sh", "shell"):
                r = subprocess.run(["bash", "-n"], input=body, text=True, capture_output=True, check=False)
                blocks.append({"source": src, "block": i, "language": lang, "syntax": "pass" if r.returncode == 0 else "FAIL " + r.stderr[:80]})
            elif lang in ("python", "py"):
                try:
                    ast.parse(body)
                    ok = "pass"
                except SyntaxError as exc:
                    ok = "FAIL " + str(exc)[:80]
                blocks.append({"source": src, "block": i, "language": lang, "syntax": ok})
    fails = [b for b in blocks if b["syntax"] != "pass"]
    if fails:
        fail(f"fenced block syntax failures: {fails[:3]}")
    ex = []
    for p in sorted(HERE.glob("examples/**/*.py")):
        ast.parse(p.read_text())
        ex.append(str(p.relative_to(HERE)))
    for p in sorted(HERE.glob("examples/native_phase25_example/*.json")):
        json.loads(p.read_text())
    return blocks, ex


def historical_guards(meta: dict) -> dict:
    old = json.loads(base_blob("docs/manuals/release_metadata.json"))
    for k in HISTORIC_META_KEYS:
        if meta[k] != old[k]:
            fail(f"historical metadata block {k!r} differs from the base commit (C1 / N15 / Phase 2 identities must never change)")
    fixture = {}
    for f in sorted((HERE / "examples/native9f_metadata").rglob("*")):
        if f.is_file():
            rel = "docs/manuals/" + f.relative_to(HERE).as_posix()
            fixture[rel] = base_blob(rel) == f.read_bytes()
    if not fixture or not all(fixture.values()):
        fail(f"native9f metadata fixture differs from the base commit: {[k for k, v in fixture.items() if not v][:3]}")
    tracked = [p for p in subprocess.run(["git", f"--git-dir={GIT_DIR}", "ls-tree", "-r", "--name-only", BASE, "docs/manuals", "docs/subsurface_hydrology"], capture_output=True, text=True, check=False).stdout.split()]
    if len(tracked) < 200:
        fail("the base listing is implausibly small; refusing to treat an empty list as a pass")
    drift = []
    for rel in tracked:
        p = DOCS.parent / rel
        if rel in ALLOWED_CHANGED:
            continue
        if not p.is_file() or sha(p.read_bytes()) != sha(base_blob(rel)):
            drift.append(rel)
    if drift:
        fail(f"{len(drift)} historical file(s) differ from the base commit outside the allowed list: {drift[:5]}")
    auth = DOCS / "subsurface_hydrology"
    copies = {}
    for f in sorted((HERE / "qualification").glob("*")):
        if f.is_file() and (auth / f.name).is_file():
            copies[f.name] = f.read_bytes() == (auth / f.name).read_bytes()
    if not all(copies.values()):
        fail(f"qualification copies differ from the authoritative files: {[k for k, v in copies.items() if not v]}")
    return {"metadata_blocks_equal_base": list(HISTORIC_META_KEYS), "native9f_fixture_files": len(fixture), "historical_files_checked_byte_equal_to_base": len(tracked) - len(ALLOWED_CHANGED & set(tracked)),
            "allowed_changed_files": sorted(ALLOWED_CHANGED & set(tracked)), "qualification_copies_equal_authoritative": len(copies)}


def final_cross_checks(meta: dict) -> dict:
    p25 = meta["native_phase25"]
    sub = DOCS / "subsurface_hydrology"
    man, acc, pub, cap = sub / "phase25_source_manifest.json", sub / "phase25_qualification.json", sub / "phase25_publication.json", sub / "phase25_source_capsule.zip"
    for f in (man, acc, pub, cap, sub / "phase25_qualification.md"):
        if not f.is_file():
            fail(f"final mode needs the Root-supplied {f.name}; it does not exist (nothing is fabricated)")
    manifest = json.loads(man.read_text())
    if manifest.get("digest_sha256") != p25["syrup_package_sha256"] or len(manifest.get("files", [])) != p25["package_file_count"] or sha(man.read_bytes()) != p25["source_manifest_sha256"]:
        fail("native_phase25 package / file count / manifest hash differ from phase25_source_manifest.json")
    if sha(acc.read_bytes()) != p25["whole_phase_acceptance_sha256"]:
        fail("native_phase25.whole_phase_acceptance_sha256 differs from phase25_qualification.json")
    receipt = json.loads(acc.read_text())
    if receipt.get("source_manifest_sha256") != p25["source_manifest_sha256"] or receipt.get("source_package_sha256") != p25["syrup_package_sha256"] or receipt["dependencies"]["LEAF_revision"] != p25["leaf_source_commit"]:
        fail("the Root qualification receipt does not name the metadata's source manifest / package / LEAF revision")
    publication = json.loads(pub.read_text())
    expect = {("source", "commit"): p25["source_commit"], ("source", "branch"): p25["source_branch"], ("source", "package_sha256"): p25["syrup_package_sha256"], ("source", "file_count"): p25["package_file_count"],
              ("source", "source_manifest_sha256"): p25["source_manifest_sha256"], ("source", "source_capsule_sha256"): sha(cap.read_bytes()), ("leaf", "commit"): p25["leaf_source_commit"],
              ("leaf", "branch"): p25["leaf_source_branch"], ("leaf", "package_sha256"): p25["leaf_package_sha256"], ("qualification", "receipt_sha256"): sha(acc.read_bytes()),
              ("qualification", "human_readable_sha256"): sha((sub / "phase25_qualification.md").read_bytes())}
    wrong = [f"{a}.{b}" for (a, b), v in expect.items() if publication.get(a, {}).get(b) != v]
    if wrong or publication.get("main_integration") is not None:
        fail(f"phase25_publication.json differs from the metadata / records ({wrong}) or records a main integration that is not yet made")
    # the exact-code capsule: every manifest file must be in it with the manifest hash, and nothing else
    try:
        z = zipfile.ZipFile(cap)
        bad = z.testzip()
    except (zipfile.BadZipFile, OSError, zlib_error) as exc:
        fail(f"phase25_source_capsule.zip is unreadable ({type(exc).__name__})")
    if bad is not None:
        fail("phase25_source_capsule.zip has a CRC failure")
    inside = {n[len("src/maple_syrup/"):]: sha(z.read(n)) for n in z.namelist() if n.startswith("src/maple_syrup/")}
    if len(z.namelist()) != len(inside) or inside != {e["path"]: e["sha256"] for e in manifest["files"]}:
        fail("phase25_source_capsule.zip is not exactly the manifest's source files")
    return {"phase25_manifest_sha256": sha(man.read_bytes()), "phase25_acceptance_sha256": sha(acc.read_bytes()), "phase25_publication_sha256": sha(pub.read_bytes()), "phase25_source_capsule_sha256": sha(cap.read_bytes()),
            "capsule_files_equal_manifest": len(inside)}


ARCHIVE_SKIP = frozenset({"SYRUP_Manuals_and_Examples.zip", "archive_manifest.json"})


